def worktree_busy(wt: Path, cache: dict | None = None) -> str | None:
    """Why `wt`'s build output must not be reclaimed, or None.

    Probes the WORKTREE, never the artifact directory: a compiler does not sit
    in `target/`, it sits in the source root and writes into it. Probing the
    artifact dir would answer "nobody home" for exactly the build this exists to
    protect. An absent or broken probe REFUSES — the bottom pressure rung sets
    the idle threshold to zero days, which every worktree passes, so this gate
    and the session lock are all that stand between an actively-compiling tree
    and losing its cache.
    """
    if _process_busy_reason is None:
        return ("process-liveness helper unavailable in this _lib deploy; "
                "refusing every deletion")
    return _process_busy_reason(wt, cache=cache)


# Directory names that are ALWAYS regenerable build output.
ALWAYS = {"node_modules", ".venv", ".next", ".turbo"}
# Reclaimed only when a sibling file proves it is build output, not source.
CONDITIONAL = {"target": "Cargo.toml"}

# Session machinery, never source — excluded from the idle reading for the same
# reason the root dir is (defect [1]): a file the TOOLING writes must not look
# like a human edit. A session lock is touched by every session that opens the
# worktree, so counting it would make a worktree read "active" for a full idle
# window after the last session ended — and, since the lock is checked AFTER the
# idle threshold, the honest "preserved: live session lock" report would never
# print. Liveness is decided by has_live_session_lock(), on the lock's own clock.
SKIP_SOURCE_NAMES = {".session-lock", ".session-lock.json"}

# Free space -> idle threshold (days). Each rung's trigger is
# max(absolute_gb, pct_of_volume), mirroring the proportional floor in
# hooks/worktree-footprint-signal.py: a flat number does not scale with the disk.
# 150 GB free is comfortable on a 500 GB laptop and a five-alarm fire on a 4 TB
# workstation, so the rungs scale with the volume and the absolute values act as
# floors for small disks. Ascending caps, first match wins; above the last rung
# the tool is a no-op, so a healthy disk keeps every build cache warm. The 0.0
# rung exists so the floor is defended even when every worktree is freshly built.
#
# Raised 2026-10-16. The old ladder (20/40/80/150 GB -> 0/1/3/7 d) held a 1 TB
# disk at 41-65 GB free (~5%) for days: Rust worktrees arrive at 5-15 GB each,
# faster than any of them reaches 3 days idle. A 12-hour-idle manual pass
# reclaimed 118 GB the 3-day rung could not see. The process probe and the
# session lock, not idle age, protect a running build, so short rungs are safe;
# the output is regenerable, and the cost of reclaiming early is a rebuild.
#   (pct_of_volume, absolute_gb, idle_days)
PRESSURE_LADDER = (
    (0.04, 40.0, 0.0),
    (0.09, 80.0, 0.5),
    (0.16, 150.0, 1.0),
    (0.27, 250.0, 3.0),
)

# Walk guard: a source tree is small once artifact dirs are skipped, but a
# pathological checkout must not stall the whole fleet run. A walk that hits this
# bound has NOT seen the whole source, so its idle reading is a partial sample —
# see idle_days(), which reports truncation rather than trusting it.
MAX_SOURCE_ENTRIES = 40_000


def ladder_idle_days(free_gb: float, total_gb: float | None = None):
    """Idle threshold for the current free space, or None when there is no pressure.

    total_gb=None keeps the pure absolute ladder (the small-disk floor), so the
    arithmetic is testable without faking a volume.
    """
    for pct, absolute, idle in PRESSURE_LADDER:
        cap = absolute if total_gb is None else max(absolute, total_gb * pct)
        if free_gb < cap:
            return idle
    return None


def ladder_caps(total_gb: float | None = None) -> list[float]:
    """The effective trigger (GB free) of each rung, for reporting and controls."""
    return [absolute if total_gb is None else max(absolute, total_gb * pct)
            for pct, absolute, _ in PRESSURE_LADDER]


def idle_days(wt: Path, now: float) -> tuple[float, str | None]:
    """(days since the worktree's SOURCE was last touched, unmeasurable_reason).

    A non-None reason means the reading cannot be trusted and the caller must
    preserve. It is a REASON rather than a flag so the report can say which.

    Newest mtime over source entries, skipping .git and every artifact dir. The
    worktree ROOT is deliberately excluded: its mtime bumps whenever an entry is
    created or removed inside it, so `cargo build` writing target/ would mark the
    worktree "active" and protect the very artifact this tool exists to reclaim.

    The truncation flag is load-bearing. A walk that stops at MAX_SOURCE_ENTRIES
    has seen only a PREFIX of the source, and the file someone edited an hour ago
    may sit in the unvisited remainder — so a partial walk can report a worktree
    as idle precisely when it is in active use. The caller preserves on
    truncation and says so; this tool deletes, so an unknown reads as "in use".

    The same applies to a walk that reads NOTHING. Every lstat here is guarded,
    because one unreadable entry must not abort a fleet run — but if EVERY entry
    fails (a permissions problem, a dataless cloud placeholder, a half-mounted
    volume) the newest-mtime is still 0.0, which reads as infinitely idle and
    would delete the artifacts of a worktree we could not measure at all. So
    "measured nothing" is reported as unmeasurable, exactly like truncation, and
    never as maximally stale.
    """
    best = 0.0
    seen = 0
    truncated: str | None = None
    for root, dirs, files in os.walk(wt, topdown=True, onerror=lambda e: None):
        for d in list(dirs):
            if d == ".git" or d in ALWAYS or (
                d in CONDITIONAL and (Path(root) / CONDITIONAL[d]).exists()
            ):
                dirs.remove(d)
        # Sub-directories still carry signal (a new source dir is real activity);
        # only the root is excluded, and os.walk yields it first.
        entries = files if Path(root) == wt else files + dirs
        for name in entries:
            if name in SKIP_SOURCE_NAMES:
                continue
            try:
                best = max(best, os.lstat(os.path.join(root, name)).st_mtime)
            except OSError:
                pass
            seen += 1
        if seen > MAX_SOURCE_ENTRIES:
            truncated = (f"source walk exceeded {MAX_SOURCE_ENTRIES} entries, "
                         f"so the idle reading is only a prefix of the source")
            break
    if not best:
        # Nothing readable: unmeasurable, not "infinitely idle".
        return 0.0, ("no source entry could be read (permissions, a dataless "
                     "cloud placeholder, or a worktree with no source at all)")
    return (now - best) / 86400, truncated


def dir_size_mb(p: Path) -> int:
    # A symlinked artifact costs nothing here and its target may live outside the
    # worktree — never follow it, never bill it.
    if is_link(p):
        return 0
    total = 0
    for root, _dirs, files in os.walk(p, onerror=lambda e: None):
        for f in files:
            try:
                total += os.lstat(os.path.join(root, f)).st_size
            except OSError:
                pass
    return total // (1024 * 1024)


def is_link(p: Path) -> bool:
    """Symlink, or a Windows junction (which is not a symlink to os.path)."""
    try:
        if p.is_symlink():
            return True
    except OSError:
        return False
    isjunction = getattr(os.path, "isjunction", None)
    if isjunction is not None:
        try:
            return bool(isjunction(p))
        except OSError:
            return False
    return False


# Liveness is decided by _lib.has_live_session_lock, never a copy living here.
# This file shipped with its own, which probed `<wt>/.session-lock` — a filename
# that exists nowhere on a real machine — so the guard was dead in production
# while reading, correctly, as "no session here". At the 0-day pressure rung
# every worktree passes the idle gate, which makes this the ONLY protection
# between an actively-compiling worktree and losing its `target/`.


def find_artifacts(wt: Path):
    """Yield reclaimable artifact dirs inside one worktree, never descending into them."""
    for root, dirs, _files in os.walk(wt, topdown=True, onerror=lambda e: None):
        for d in list(dirs):
            full = Path(root) / d
            if d == ".git":
                dirs.remove(d)
            elif d in ALWAYS:
                dirs.remove(d)          # do not descend into what we delete
                yield full
            elif d in CONDITIONAL and (Path(root) / CONDITIONAL[d]).exists():
                dirs.remove(d)
                yield full


# How far below a dev-root entry to look for checkouts it only GROUPS
# (`<root>/<batch>/<checkout>`, or an agent's `<day>/<chat>/work/<group>/<clone>`).
GROUP_DEPTH = 4


def is_checkout(p: Path) -> bool:
    """A `.git` dir (clone) or `.git` file (linked worktree)."""
    try:
        return (p / ".git").exists()
    except OSError:
        return False


def checkouts_within(d: Path, depth: int) -> list:
    """Checkouts up to `depth` levels below d. Never enters a checkout or an
    artifact dir: a git dependency in node_modules has a `.git` too."""
    try:
        subdirs = sorted(p for p in d.iterdir() if p.is_dir() and not is_link(p))
    except OSError:
        return []
    out = []
    for s in subdirs:
        if s.name in ALWAYS or s.name in CONDITIONAL:
            continue
        if is_checkout(s):
            out.append(s)
        elif depth > 1:
            out.extend(checkouts_within(s, depth - 1))
    return out


def discover_units(dev_root: Path, skipped: list) -> list:
    """Every checkout under the root, each judged as its own unit."""
    if not dev_root.is_dir():
        return []
    try:
        entries = sorted(os.listdir(dev_root))
    except OSError as e:
        skipped.append(f"{dev_root}: unreadable ({e})")
        return []
    # A folder that only GROUPS checkouts is judged per checkout. As one unit it
    # read "active" while any member was in use, or overran MAX_SOURCE_ENTRIES
    # and was preserved whole: ~25 idle checkouts (90 GB) under one such folder
    # were never reclaimed (2026-10-28). Known limits, all regenerable: a session
    # whose cwd is the group itself (not a member) no longer shields the members;
    # a non-git project with a vendored clone has that clone judged alone; and
    # build output loose beside the checkouts is left in place.
    units = []
    for name in entries:
        top = dev_root / name
        if not top.is_dir() or is_link(top):
            continue
        grouped = [] if is_checkout(top) else checkouts_within(top, GROUP_DEPTH)
        units.extend(grouped or [top])
    return units


def plan(dev_root: Path, min_idle: float, now: float) -> tuple[list, list]:
    """(reclaimable artifacts, skipped-worktree notes). Never silently drops one."""
    out: list = []
    skipped: list = []
    # One process-table reading for the whole planning pass. The apply loop takes
    # its OWN, because sizing every candidate can take minutes and a build can
    # start in that window.
    probe_cache: dict = {}
    for wt in discover_units(dev_root, skipped):
        entry = os.path.relpath(wt, dev_root)
        age, unmeasurable = idle_days(wt, now)
        if unmeasurable:
            # Fail LOUD, not silent: an unmeasurable worktree is reported with
            # its reason, so a client can see why their biggest checkout is
            # never reclaimed instead of assuming the pass covered it.
            skipped.append(f"{entry}: {unmeasurable} — preserved")
            continue
        if age < min_idle:
            continue
        if has_live_session_lock(wt, now):
            skipped.append(f"{entry}: live session lock, preserved")
            continue
        # The session lock is a PROXY and fails OPEN: it depends on a writer that
        # stops emitting during one long call, and its own probe falls through to
        # lock files when it cannot measure. A running compiler is direct
        # evidence and fails CLOSED.
        busy = worktree_busy(wt, probe_cache)
        if busy:
            skipped.append(f"{entry}: {busy}, preserved")
            continue
        for art in find_artifacts(wt):
            out.append({"worktree": str(wt), "path": str(art),
                        "idle_days": round(age, 1)})
    return out, skipped


# A variant not built for this long is stale, unless it is among its name's
# KEEP_NEWEST newest. Two, not one: a library's unit tests, a same-named binary
# and its benches all share one name, so "newest only" would trim the test
# binary of a copy that last ran `cargo build`.
STALE_VARIANT_HOURS = 24.0
KEEP_NEWEST = 2
# `<name>-<16 hex>` then the end or a dot: `foo-0123456789abcdef`, `.d`, `.exe`,
# `.pdb`, `.dSYM`, `.<cgu>.rcgu.o`. Binary names may carry dashes.
_DEPS_RE = re.compile(r"^(?P<crate>[A-Za-z0-9_-]+)-(?P<hash>[0-9a-f]{16})(?:\.|$)")
# `incremental/<crate>-<id>`: one cache per crate variant.
_INCR_RE = re.compile(r"^(?P<crate>[A-Za-z0-9_-]+)-(?P<id>[0-9a-z]+)$")
# rustc writes these at the end of every incremental session. Their mtime is the
# real build time; a session dir's own mtime is not (copying a target/ resets it).
_INCR_SESSION_FILES = ("dep-graph.bin", "query-cache.bin", "work-products.bin")


def _mtime(p: Path) -> float:
    try:
        return os.lstat(p).st_mtime
    except OSError:
        return 0.0


def _paths_size_mb(paths, seen: set) -> float:
    """Size of files and dirs, each inode once: rustc hard-links a variant's
    objects between `deps` and `incremental`, so a plain sum bills them twice."""
    total = 0
    stack = list(paths)
    while stack:
        p = stack.pop()
        try:
            st = os.lstat(p)
        except OSError:
            continue
        if stat.S_ISDIR(st.st_mode):
            try:
                stack.extend(Path(p) / c for c in os.listdir(p))
            except OSError:
                pass
            continue
        key = (st.st_dev, st.st_ino)
        if key not in seen:
            seen.add(key)
            total += st.st_size
    return total / (1024 * 1024)


def profile_dirs(target: Path) -> list:
    """`target/<profile>` and `target/<triple>/<profile>` dirs that hold builds.
    A symlinked `target` is never followed: it may be shared with copies this
    pass never probed."""
    out = []
    if is_link(target):
        return out
    try:
        level1 = [c for c in target.iterdir() if c.is_dir() and not is_link(c)]
    except OSError:
        return out
    for c in level1:
        if (c / "deps").is_dir() or (c / "incremental").is_dir():
            out.append(c)
            continue
        try:
            out.extend(g for g in c.iterdir() if g.is_dir() and not is_link(g)
                       and ((g / "deps").is_dir() or (g / "incremental").is_dir()))
        except OSError:
            pass
    return out


def _is_executable(p: Path) -> bool:
    try:
        st = os.lstat(p)
    except OSError:
        return False
    if not stat.S_ISREG(st.st_mode):
        return False
    return p.suffix == ".exe" or os.name == "nt" or bool(st.st_mode & stat.S_IXUSR)


def _group_newest(paths) -> float:
    return max(_mtime(p) for p in paths)


def stale_binary_variants(deps: Path, now: float, hours: float) -> list:
    """Groups of paths, one per stale linked-binary variant in `deps`.

    A variant counts only when its group holds the linked executable itself
    (`<name>-<hash>`, or `.exe`); libraries and their loose objects never do.
    Each name keeps its KEEP_NEWEST newest variants whatever their age. The
    executable comes first in each group, so a failed delete (a running `.exe`
    on Windows) leaves the group whole.
    """
    if is_link(deps):
        return []
    try:
        names = os.listdir(deps)
    except OSError:
        return []
    groups: dict = {}
    for n in names:
        m = _DEPS_RE.match(n)
        if m:
            groups.setdefault((m["crate"], m["hash"]), []).append(n)
    by_crate: dict = {}
    for (crate, hsh), members in groups.items():
        stem = f"{crate}-{hsh}"
        exes = [n for n in members if n in (stem, stem + ".exe")
                and _is_executable(deps / n)]
        if not exes:
            continue
        paths = [deps / n for n in exes] + [deps / n for n in members if n not in exes]
        if any(is_link(p) for p in paths):
            continue
        by_crate.setdefault(crate, []).append((_group_newest(paths), paths))
    out = []
    for variants in by_crate.values():
        variants.sort(key=lambda v: -v[0])
        for newest, paths in variants[KEEP_NEWEST:]:
            if now - newest >= hours * 3600:
                out.append(paths)
    return out


def incremental_newest(d: Path) -> float:
    """When rustc last finished a session in this cache: the newest of its lock
    files and each session's own files (the session dir's mtime as a fallback,
    e.g. a session still running)."""
    newest = 0.0
    try:
        children = list(d.iterdir())
    except OSError:
        return _mtime(d)
    for c in children:
        if is_link(c):
            continue
        if c.is_dir():
            marks = [_mtime(c / f) for f in _INCR_SESSION_FILES if (c / f).exists()]
            newest = max([newest] + (marks or [_mtime(c)]))
        else:
            newest = max(newest, _mtime(c))
    return newest or _mtime(d)


def stale_incremental(incr: Path, now: float, hours: float) -> list:
    """Stale per-variant incremental caches, keeping each name's newest."""
    if is_link(incr):
        return []
    try:
        names = os.listdir(incr)
    except OSError:
        return []
    by_crate: dict = {}
    for n in names:
        m = _INCR_RE.match(n)
        d = incr / n
        # Every package's build script is named `build_script_build`, so "newest
        # per crate" cannot tell them apart; they are small, so leave them.
        if not m or m["crate"].startswith("build_script_") or is_link(d) or not d.is_dir():
            continue
        by_crate.setdefault(m["crate"], []).append((incremental_newest(d), d))
    out = []
    for caches in by_crate.values():
        caches.sort(key=lambda c: -c[0])
        out.extend([d] for newest, d in caches[KEEP_NEWEST:] if now - newest >= hours * 3600)
    return out


def _variant_newest(paths) -> float:
    """Re-read at apply time: a copy in use may have rebuilt it since the plan."""
    first = Path(paths[0])
    if first.is_dir() and first.parent.name == "incremental":
        return incremental_newest(first)
    return _group_newest(map(Path, paths))


def _trim_busy(wt: Path, now: float, cache: dict) -> str | None:
    """worktree_busy, plus the session lock where no process probe exists (the
    probe answers None there, and the trim works inside copies in use)."""
    busy = worktree_busy(wt, cache)
    if busy:
        return busy
    supported = getattr(_worktree_safety, "probe_supported", None)
    if supported is not None and not supported() and has_live_session_lock(wt, now):
        return "live session lock (no process probe on this platform)"
    return None


def trim_plan(dev_root: Path, now: float, hours: float = STALE_VARIANT_HOURS):
    """(stale variants, skipped notes) across every copy, in use or not."""
    skipped: list = []
    items: list = []
    probe_cache: dict = {}
    seen_inodes: set = set()
    for wt in discover_units(dev_root, skipped):
        targets = [t for t in find_artifacts(wt)
                   if t.name in CONDITIONAL and not is_link(t)]
        if not targets:
            continue
        found = []
        for t in targets:
            for prof in profile_dirs(t):
                found += stale_binary_variants(prof / "deps", now, hours)
                found += stale_incremental(prof / "incremental", now, hours)
        if not found:
            continue
        busy = _trim_busy(wt, now, probe_cache)
        if busy:
            skipped.append(f"{os.path.relpath(wt, dev_root)}: {busy}, "
                           f"its stale build variants preserved")
            continue
        for paths in found:
            items.append({"worktree": str(wt), "paths": [str(p) for p in paths],
                          "size_mb": round(_paths_size_mb(paths, seen_inodes), 1)})
    return items, skipped


def trim(a: argparse.Namespace, dev_root: Path, now: float) -> dict:
    """Plan and, with --apply, delete stale build variants. Returns a summary."""
    items, skipped = trim_plan(dev_root, now)
    apply = getattr(a, "apply_trim", a.apply)
    deleted, failed, fresh = 0, [], 0
    if apply and items:
        ldir = log_dir()
        ldir.mkdir(parents=True, exist_ok=True)
        stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d")
        manifest = ldir / f"build-reclaim-{stamp}.jsonl"
        apply_probe_cache: dict = {}   # fresh, as in reclaim(): sizing took time
        refused: set = set()
        with open(manifest, "a", encoding="utf-8") as mf:
            for it in items:
                wt = it["worktree"]
                if wt in refused:
                    continue
                busy = _trim_busy(Path(wt), time.time(), apply_probe_cache)
                if busy:
                    refused.add(wt)
                    skipped.append(f"{os.path.relpath(wt, dev_root)}: {busy} at "
                                   f"apply time, its stale build variants preserved")
                    continue
                if time.time() - _variant_newest(it["paths"]) < STALE_VARIANT_HOURS * 3600:
                    fresh += 1          # rebuilt since the plan: keep it
                    continue
                try:
                    for p in map(Path, it["paths"]):
                        if p.is_dir() and not is_link(p):
                            remove_artifact(p)
                        else:
                            p.unlink(missing_ok=True)
                    deleted += 1
                    mf.write(json.dumps({**it, "kind": "stale-build-variant",
                                         "ts": datetime.now(timezone.utc).isoformat()})
                             + "\n")
                except OSError as e:
                    failed.append(f"{it['paths'][0]}: {e}")
    if fresh:
        skipped.append(f"{fresh} variant(s) rebuilt since the plan, preserved")
    _bank_first_report(a, len(items), marker=TRIM_FIRST_REPORT_MARKER, applying=apply)
    return {"variants": len(items), "deleted": deleted, "failed": failed,
            "skipped": skipped, "applied": apply,
            "worktrees": len({i["worktree"] for i in items}),
            "size_gb": round(sum(i["size_mb"] for i in items) / 1024, 1),
            "stale_hours": STALE_VARIANT_HOURS}


def print_trim(t: dict) -> None:
    if not (t["variants"] or t["skipped"] or t["failed"]):
        return
    verb = "TRIMMED" if t["applied"] else "WOULD TRIM"
    print(f"{verb}: {t['variants']} stale build variant(s), {t['size_gb']:.1f} GB "
          f"across {t['worktrees']} copy(ies) (not built in {t['stale_hours']:.0f} h; "
          f"each name's {KEEP_NEWEST} newest kept)")
    for line in t["skipped"][:5]:
        print(f"    {line}")
    if t["failed"]:
        print(f"  {len(t['failed'])} failed:", *t["failed"][:5], sep="\n    ")


def _force_remove(func, path, _exc):
    """Windows refuses to unlink a read-only file, and cargo/npm leave plenty."""
    try:
        os.chmod(path, stat.S_IWRITE)
    except OSError:
        raise
    func(path)


def remove_artifact(p: Path) -> None:
    # rmtree refuses a symlink; unlinking drops the pointer without ever
    # following it out of the worktree.
    if is_link(p):
        try:
            p.unlink()
        except (OSError, IsADirectoryError, PermissionError):
            os.rmdir(p)          # Windows junction
        return
    if sys.version_info >= (3, 12):
        shutil.rmtree(p, onexc=_force_remove)
    else:
        shutil.rmtree(p, onerror=_force_remove)


def disk(path: Path):
    """Usage of the volume the dev root actually lives on, not the home volume —
    a client's code may sit on a second drive, and defending the wrong volume's
    floor is the same as defending none."""
    for p in (path, Path.home()):
        try:
            return shutil.disk_usage(str(p))
        except OSError:
            continue
    return None


def log_dir() -> Path:
    override = os.environ.get("DEV_BUILD_RECLAIM_LOG_DIR", "").strip()
    if override:
        return Path(override).expanduser()
    return Path.home() / ".claude" / "logs" / "dev-repo-reaper"


# Banked by the scheduled check's first run that finds something to reclaim.
# --auto-gc applies once that report is a day old, so, like the daily pass, it
# deletes nothing on the day it first reports. It keeps its own marker: the
# daily pass banks one only after its idle gate, which a laptop that sleeps
# through 04:30 and wakes to someone typing can defer for good.
FIRST_REPORT_MARKER = Path.home() / ".claude" / ".build-reclaim-first-report"
# The trim keeps its own day: a trim finding on a healthy disk must not arm the
# whole-folder reclaim, which has not reported anything yet.
TRIM_FIRST_REPORT_MARKER = Path.home() / ".claude" / ".build-trim-first-report"


def reclaim_roots() -> list:
    """The dev root, then ~/dev, ~/code and ~/.codex/worktrees when they exist,
    each listed once."""
    roots = [resolve_dev_root()]
    seen = {os.path.normcase(os.path.realpath(roots[0]))}
    for extra in (Path.home() / "dev", Path.home() / "code",
                  Path.home() / ".codex" / "worktrees"):
        key = os.path.normcase(os.path.realpath(extra))
        if key not in seen and extra.is_dir():
            roots.append(extra)
            seen.add(key)
    return roots


def main() -> int:
    ap = argparse.ArgumentParser(
        description="Reclaim regenerable build artifacts from idle worktrees.")
    ap.add_argument("--apply", action="store_true", help="actually delete (default: dry-run)")
    ap.add_argument("--auto-gc", action="store_true",
                    help="the scheduled check: reports first, applies once that report is a day old")
    ap.add_argument("--min-idle-days", type=float, default=None,
                    help="pin the idle threshold; default scales with free space (PRESSURE_LADDER)")
    ap.add_argument("--min-free-gb", type=float, default=None,
                    help="no-op unless free space is below this (for cron: only act under pressure)")
    ap.add_argument("--dev-root", help="this root only (default: the dev root, ~/dev, ~/code, "
                                       "~/.codex/worktrees)")
    ap.add_argument("--json", action="store_true", help="machine-readable plan, one per root")
    a = ap.parse_args()

    a.apply_trim = a.apply
    if a.auto_gc:
        def day_old(marker: Path) -> bool:
            try:
                return time.time() - marker.stat().st_mtime >= 86400
            except OSError:  # no first report yet
                return False
        a.apply = a.apply or day_old(FIRST_REPORT_MARKER)
        a.apply_trim = a.apply_trim or day_old(TRIM_FIRST_REPORT_MARKER)
    roots = [Path(a.dev_root).expanduser()] if a.dev_root else reclaim_roots()
    return max(reclaim(a, root) for root in roots)


def _bank_first_report(a: argparse.Namespace, found: int, marker: Path | None = None,
                       applying: bool | None = None) -> None:
    """--auto-gc: the first run that finds something only reports, and banks the date."""
    marker = marker or FIRST_REPORT_MARKER
    applying = a.apply if applying is None else applying
    if getattr(a, "auto_gc", False) and not applying and found and not marker.exists():
        marker.parent.mkdir(parents=True, exist_ok=True)
        marker.touch()


def reclaim(a: argparse.Namespace, dev_root: Path) -> int:
    if not a.json:
        print(f"[{dev_root}]")
    usage = disk(dev_root)
    if usage is None:
        msg = f"cannot stat the volume holding {dev_root} — refusing to guess"
        print(json.dumps({"error": msg}) if a.json else f"dev-build-reclaim: {msg}",
              file=sys.stderr)
        return 2
    before = usage.free / (1024 ** 3)
    total = usage.total / (1024 ** 3)

    if a.min_free_gb is not None and before >= a.min_free_gb:
        msg = f"free {before:.0f} GB >= threshold {a.min_free_gb:.0f} GB — no-op"
        print(json.dumps({"skipped": msg}) if a.json else msg)
        return 0

    # Stale build variants go on every run, pressure or not: they are waste in
    # copies that are in use, which the idle-gated reclaim below never touches.
    now = time.time()
    trimmed = trim(a, dev_root, now)
    # The ladder reads the free space AFTER the trim: a trim that freed 150 GB
    # must not leave the 0-day rung deleting whole target/ folders for nothing.
    ladder_free = before
    if trimmed["deleted"]:
        ladder_free = (disk(dev_root) or usage).free / (1024 ** 3)

    if a.min_idle_days is not None:
        min_idle, tier = a.min_idle_days, "pinned by --min-idle-days"
    else:
        laddered = ladder_idle_days(ladder_free, total)
        if laddered is None:
            top = ladder_caps(total)[-1]
            msg = (f"free {ladder_free:.0f} GB >= {top:.0f} GB "
                   f"({total:.0f} GB volume) — no pressure, whole-folder reclaim is a no-op")
            if a.json:
                print(json.dumps({"skipped": msg, "trim": trimmed}))
            else:
                print_trim(trimmed)
                print(msg)
            return 0
        min_idle = laddered
        tier = f"pressure ladder @ {ladder_free:.0f} GB free of {total:.0f} GB"

    items, skipped = plan(dev_root, min_idle, now)
    for it in items:
        it["size_mb"] = dir_size_mb(Path(it["path"]))
    # Largest first: a pressure-triggered run must buy back the most space in its
    # first seconds, not its last.
    items.sort(key=lambda i: -i["size_mb"])

    total_mb = sum(i["size_mb"] for i in items)
    worktrees = {i["worktree"] for i in items}

    deleted, failed = 0, []
    if a.apply and items:
        ldir = log_dir()
        ldir.mkdir(parents=True, exist_ok=True)
        stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d")
        manifest = ldir / f"build-reclaim-{stamp}.jsonl"
        # Builtin open with an explicit positional mode, not Path.open("a"): the
        # cloud-safe-walker gate proves write-only from `open(path, MODE)` and
        # cannot see the mode when it is Path.open's first argument, so the
        # append would read to it as a recursive content read.
        # A FRESH probe, not plan()'s. Sizing every candidate above walks hundreds
        # of gigabytes and can take minutes; on a shared machine a liveness
        # reading has a shelf life measured in minutes, so it is re-taken here,
        # immediately before the first deletion.
        apply_probe_cache: dict = {}
        with open(manifest, "a", encoding="utf-8") as mf:
            for it in items:
                busy = worktree_busy(Path(it["worktree"]), apply_probe_cache)
                if busy:
                    skipped.append(f"{os.path.relpath(it['worktree'], dev_root)}: "
                                   f"{busy} at apply time, preserved")
                    continue
                try:
                    remove_artifact(Path(it["path"]))
                    deleted += 1
                    mf.write(json.dumps({**it, "ts": datetime.now(timezone.utc).isoformat()}) + "\n")
                except OSError as e:
                    failed.append(f"{it['path']}: {e}")
    _bank_first_report(a, len(items))

    after = (disk(dev_root) or usage).free / (1024 ** 3)
    result = {
        "dirs": len(items), "worktrees": len(worktrees),
        "size_gb": round(total_mb / 1024, 1), "applied": a.apply,
        "deleted": deleted, "failed": failed, "skipped": skipped,
        "dev_root": str(dev_root),
        "free_gb_before": round(before, 1), "free_gb_after": round(after, 1),
        "volume_gb": round(total, 1),
        "min_idle_days": min_idle, "threshold_source": tier,
        "trim": trimmed,
    }

    if a.json:
        print(json.dumps(result, indent=1))
        return 0

    per_wt: dict[str, int] = {}
    for i in items:
        per_wt[i["worktree"]] = per_wt.get(i["worktree"], 0) + i["size_mb"]
    for wt, mb in sorted(per_wt.items(), key=lambda kv: -kv[1])[:12]:
        print(f"  {mb/1024:6.1f} GB  {os.path.relpath(wt, dev_root)}")

    print_trim(trimmed)
    verb = "RECLAIMED" if a.apply else "WOULD RECLAIM"
    print(f"\n{verb}: {len(items)} dirs, {total_mb/1024:.1f} GB across "
          f"{len(worktrees)} worktree(s) (source idle >= {min_idle}d — {tier})")
    if skipped:
        print(f"  {len(skipped)} worktree(s) preserved:", *skipped[:5], sep="\n    ")
    if failed:
        print(f"  {len(failed)} failed:", *failed[:5], sep="\n    ")
    if a.apply:
        print(f"  free: {before:.0f} GB -> {after:.0f} GB")
    else:
        print("Re-run with --apply to execute.")
    return 0


if __name__ == "__main__":
    # Windows cp1252-console safety (#313): the output carries non-ASCII (the em
    # dashes and >= glyphs). An unguarded print raises UnicodeEncodeError there,
    # and a reclaim tool whose report cannot print reads as a tool that did nothing.
    for _stream in (sys.stdout, sys.stderr):
        try:
            _stream.reconfigure(encoding="utf-8")  # Python 3.7+
        except (AttributeError, ValueError):
            pass
    sys.exit(main())
